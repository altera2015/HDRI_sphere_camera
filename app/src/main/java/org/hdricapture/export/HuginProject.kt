package org.hdricapture.export

import org.hdricapture.geom.CameraFrame
import org.hdricapture.geom.Quat
import org.hdricapture.geom.Vec3
import org.hdricapture.session.Session
import java.util.Locale
import kotlin.math.atan
import kotlin.math.atan2
import kotlin.math.cos
import kotlin.math.ln
import kotlin.math.sin

/**
 * Generates a Hugin (PTOptimizer) project with initial image orientations from the gyro poses,
 * exposure values, and one stack per aim spot. Images are referenced as linear TIFFs with the same
 * base name as the DNGs (see the README in the export).
 */
object HuginProject {

    data class Orientation(val yawDeg: Double, val pitchDeg: Double, val rollDeg: Double)

    /**
     * Orientation of the stored (unrotated, sensor-oriented) image in Hugin's convention:
     * yaw positive to the right, pitch positive up, roll positive = image rotated clockwise.
     */
    fun orientation(pose: Quat, sensorOrientationDeg: Int, headingDeg: Double): Orientation {
        // Image "up" in device coordinates: device +Y rotated about the camera axis by -sensorOrientation.
        val a = Math.toRadians(-sensorOrientationDeg.toDouble())
        val imgUpDevice = Vec3(-sin(a), cos(a), 0.0)
        val forward = pose.rotate(Vec3(0.0, 0.0, -1.0))
        val imgUp = pose.rotate(imgUpDevice)
        val level = CameraFrame.looking(forward)
        val (yaw, pitch) = forward.toYawPitch()
        val roll = Math.toDegrees(atan2(imgUp dot level.right, imgUp dot level.up))
        return Orientation(normalize(yaw - headingDeg), pitch, roll)
    }

    private fun normalize(deg: Double): Double {
        var d = deg % 360.0
        if (d > 180) d -= 360
        if (d <= -180) d += 360
        return d
    }

    fun generate(session: Session, outWidth: Int = 8192): String {
        val lens = session.lens
        val longMm = maxOf(lens.sensorWidthMm, lens.sensorHeightMm)
        val hfov = Math.toDegrees(2 * atan(longMm / (2 * lens.focalLengthMm)))
        val sb = StringBuilder()
        fun f(v: Double) = String.format(Locale.US, "%.4f", v)
        sb.appendLine("# hugin project file generated by HDRI Sphere")
        sb.appendLine("#hugin_ptoversion 2")
        sb.appendLine("p f2 w$outWidth h${outWidth / 2} v360 k0 E0 R0 n\"EXR_m\"")
        sb.appendLine("m i0")
        sb.appendLine()
        var first = true
        for (cap in session.captures.sortedBy { it.spotIndex }) {
            for (frame in cap.frames) {
                val o = orientation(Quat.fromList(frame.pose), lens.sensorOrientation, session.headingDeg)
                val t = frame.exposureTimeNs * 1e-9
                val ev = log2(lens.aperture * lens.aperture / t) - log2(frame.iso / 100.0)
                val lensParams = if (first) "v${f(hfov)} a0 b0 c0 d0 e0 g0 t0" else "v=0 a=0 b=0 c=0 d=0 e=0 g=0 t=0"
                val name = frame.file.removeSuffix(".dng") + ".tiff"
                sb.appendLine(
                    "i w${lens.rawWidth} h${lens.rawHeight} f0 $lensParams Ra0 Rb0 Rc0 Rd0 Re0 Eev${f(ev)} Er1 Eb1 " +
                        "r${f(o.rollDeg)} p${f(o.pitchDeg)} y${f(o.yawDeg)} TrX0 TrY0 TrZ0 Tpy0 Tpp0 j${cap.spotIndex} " +
                        "Va1 Vb0 Vc0 Vd0 Vx0 Vy0 Vm5 n\"$name\"",
                )
                first = false
            }
        }
        sb.appendLine()
        sb.appendLine("# Optimise yaw/pitch/roll after adding control points (Hugin: Align).")
        return sb.toString()
    }

    private fun log2(x: Double) = ln(x) / ln(2.0)
}
